# Суффикс бывает не только U (unsigned): SNG06LLSB -- знаковый байт.
_AXIS = re.compile(r"^S([A-Z0-9]{2})(\d{2})([A-Z_]{2})[US][BW]$")


def axis_name(name: str, points: int | None = None) -> str:
    """
    Название опорных точек по структуре имени.

    SNM16ZUUB -> «Опорные точки: обороты, 16 (зажигание)». Величина и
    число точек берутся из имени, и число сверяется с картой: если не
    сходится, имени не даём -- значит что-то не то с самой картой.
    """
    m = _AXIS.match(name or "")
    if not m:
        return ""
    qty = AXIS_QTY.get("S" + m.group(1))
    if not qty:
        return ""
    n = int(m.group(2))
    if points is not None and points != n:
        return ""
    use = AXIS_USE.get(m.group(3))
    return "Опорные точки: %s, %d%s" % (qty, n, " (%s)" % use if use else "")


def ru_name(name: str, note: str = "", points: int | None = None) -> str:
    """Русское название или пустая строка, если уверенности нет."""
    if not name:
        return ""
    if name in CURATED:
        return CURATED[name]
    ax = axis_name(name, points)
    if ax:
        return ax
    for pref, title in PREFIX.items():
        if name.startswith(pref):
            return title
    return ""
